#!/usr/bin/env python3
"""Generates public/licenses.html from the license files of the code shipped in the web bundle.

Run after `swift package resolve` and `npm install`:  python3 Scripts/generate-licenses.py
"""
import html
from pathlib import Path

root = Path(__file__).resolve().parent.parent
checkouts = root / ".build" / "checkouts"

def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").strip()

# (name, url, note, license id) for everything compiled into WebApp.wasm or bundled into the JS.
components = [
    ("SpeedMath", "https://github.com/ainame/SpeedMath", "", "MIT-SpeedMath"),
    ("ElementaryUI", "https://github.com/elementary-swift/elementary-ui",
     "Reactivity, BrowserInterop を含む", "Apache-2.0"),
    ("Elementary", "https://github.com/elementary-swift/elementary", "", "Apache-2.0"),
    ("elementary-router", "https://github.com/ainame/elementary-router", "", "MIT-router"),
    ("JavaScriptKit", "https://github.com/swiftwasm/JavaScriptKit", "", "MIT-JavaScriptKit"),
    ("Swift Collections", "https://github.com/apple/swift-collections",
     "BasicContainers", "Apache-2.0-RLE"),
    ("browser_wasi_shim", "https://github.com/bjorn3/browser_wasi_shim",
     "MIT OR Apache-2.0（MIT を選択）", "MIT-wasi-shim"),
    ("Swift standard library", "https://github.com/swiftlang/swift",
     "Apache-2.0 with Runtime Library Exception", None),
]

licenses = {
    "MIT-SpeedMath": ("MIT License — SpeedMath", read(root / "LICENSE")),
    "MIT-router": ("MIT License — elementary-router", read(checkouts / "elementary-router" / "LICENSE")),
    "MIT-JavaScriptKit": ("MIT License — JavaScriptKit", read(checkouts / "JavaScriptKit" / "LICENSE")),
    "MIT-wasi-shim": ("MIT License — browser_wasi_shim",
                      read(root / "node_modules" / "@bjorn3" / "browser_wasi_shim" / "LICENSE-MIT")),
    "Apache-2.0": ("Apache License 2.0 — ElementaryUI, Elementary",
                   read(checkouts / "elementary-ui" / "LICENSE")),
    "Apache-2.0-RLE": ("Apache License 2.0 with Runtime Library Exception — Swift Collections",
                       read(checkouts / "swift-collections" / "LICENSE.txt")),
}

rows = "\n".join(
    f'      <li><a href="{url}">{html.escape(name)}</a>'
    + (f' <span class="note">{html.escape(note)}</span>' if note else "")
    + (f' — <a href="#{lid}">{html.escape(licenses[lid][0].split(" — ")[0])}</a>' if lid else "")
    + "</li>"
    for name, url, note, lid in components
)
sections = "\n".join(
    f'    <section id="{lid}">\n      <h2>{html.escape(title)}</h2>\n      <pre>{html.escape(text)}</pre>\n    </section>'
    for lid, (title, text) in licenses.items()
)

page = f"""<!DOCTYPE html>
<html lang="ja">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
  <title>ライセンス — スピード計算</title>
  <!-- Generated by Scripts/generate-licenses.py. Do not edit by hand. -->
  <style>
    body {{
      margin: 0; background: #fffbea; color: #3a3226;
      font-family: "Hiragino Maru Gothic ProN", "BIZ UDPGothic", system-ui, sans-serif;
    }}
    main {{ max-width: 760px; margin: 0 auto; padding: 16px; box-sizing: border-box; }}
    h1 {{ font-size: 1.4rem; }}
    h2 {{ font-size: 1rem; margin: 28px 0 8px; }}
    a {{ color: #b8650f; }}
    .back {{
      display: inline-block; padding: 5px 16px; border-radius: 999px; background: #fff;
      border: 2.5px solid #f0e2b6; color: inherit; font-weight: bold; text-decoration: none;
    }}
    ul {{ padding-left: 20px; line-height: 1.8; }}
    .note {{ font-size: 0.85rem; opacity: 0.7; }}
    pre {{
      white-space: pre-wrap; word-break: break-word; font-size: 0.75rem; line-height: 1.5;
      background: #fff; padding: 12px; border-radius: 12px; border: 2px solid #f0e2b6; max-height: 320px; overflow: auto;
    }}
  </style>
</head>
<body>
  <main>
    <a class="back" href="./">← もどる</a>
    <h1>ライセンス</h1>
    <p>このアプリには次のソフトウェアが含まれています。</p>
    <ul>
{rows}
    </ul>
{sections}
  </main>
</body>
</html>
"""
(root / "public" / "licenses.html").write_text(page, encoding="utf-8")
print("wrote public/licenses.html")
