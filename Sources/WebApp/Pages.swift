import ElementaryRouter
import ElementaryUI

@View
struct HomePage {
  @Environment(AppRoutes._routeSetEnvironmentKey) var routes
  @Environment(PlaySettings.self) var settings: PlaySettings

  var body: some View {
    section(.class("home")) {
      h2(.class("step")) { "1. カードを えらぼう" }
      div(.class("deck-grid")) {
        for deck in Deck.allCases {
          DeckButton(
            deck: deck,
            size: deck.cards(includeZero: settings.includeZero).count,
            isSelected: settings.deck == deck
          ) { settings.deck = deck }
        }
      }

      div(.class("options")) {
        div {
          h2(.class("step")) { "2. なんまい やる？" }
          div(.class("chips")) {
            // 45 is offered only for decks larger than that; on the 36-card decks it equals "all".
            if settings.deckSize > 45 {
              Chip(label: "45まい", isSelected: settings.count == 45) { settings.count = 45 }
            }
            Chip(
              label: "ぜんぶ（\(settings.deckSize)まい）",
              isSelected: settings.count <= 0 || settings.count >= settings.deckSize
            ) { settings.count = 0 }
          }
        }
        div {
          h2(.class("step")) { "3. タイマー" }
          div(.class("chips")) {
            Chip(label: "みせる", isSelected: settings.showTimer) { settings.showTimer = true }
            Chip(label: "かくす", isSelected: !settings.showTimer) { settings.showTimer = false }
          }
        }
        div {
          h2(.class("step")) { "4. 0の けいさん" }
          div(.class("chips")) {
            Chip(label: "いれない", isSelected: !settings.includeZero) { settings.includeZero = false }
            Chip(label: "いれる", isSelected: settings.includeZero) { settings.includeZero = true }
          }
        }
      }

      div(.class("start")) {
        if let routes,
          let destination = try? routes.play(
            deck: settings.deck,
            count: settings.count,
            timer: settings.showTimer,
            zero: settings.includeZero
          )
        {
          AppRoutes.Link(to: destination) { "スタート！" }
        }
      }

      // Static page generated by Scripts/generate-licenses.py, outside the router.
      a(.href("licenses.html"), .class("license-link")) { "ライセンス" }
    }
  }
}

@View
struct DeckButton {
  let deck: Deck
  let size: Int
  let isSelected: Bool
  let onSelect: () -> Void

  var body: some View {
    button(.type(.button), .class("deck \(deck.colorClass)\(isSelected ? " selected" : "")")) {
      span(.class("deck-title")) { deck.title }
      span(.class("deck-subtitle")) { deck.subtitle }
      span(.class("deck-size")) { "\(size)まい" }
    }
    .onClick { onSelect() }
  }
}

@View
struct Chip {
  let label: String
  let isSelected: Bool
  let onSelect: () -> Void

  var body: some View {
    button(.type(.button), .class(isSelected ? "chip selected" : "chip")) { label }
      .onClick { onSelect() }
  }
}

@View
struct PlayPage {
  let deck: Deck
  let count: Int
  let showTimer: Bool
  let includeZero: Bool

  var body: some View {
    // Keyed by the route values so a new deck/count/timer setting starts a fresh session, with
    // fresh state and a key listener that sees the new values.
    PlaySession(deck: deck, count: count, showTimer: showTimer, includeZero: includeZero)
      .id("\(deck.rawValue)/\(count)/\(showTimer)/\(includeZero)")
  }
}

@View
struct PlaySession {
  enum Phase {
    case ready
    case playing
    case finished
  }

  @Environment(AppRoutes._routeSetEnvironmentKey) var routes

  let deck: Deck
  let count: Int
  let showTimer: Bool
  let includeZero: Bool

  @State var phase: Phase = .ready
  @State var cards: [Card] = []
  @State var index: Int = 0
  @State var startedAt: Double = 0
  @State var elapsed: Double = 0
  @State var stamp: Stamp = .yokuDekimashita

  var body: some View {
    section(.class("play")) {
      switch phase {
      case .ready:
        div(.class("ready")) {
          p(.class("ready-deck")) { "\(deck.title)（\(deck.subtitle)）" }
          p(.class("ready-count")) { "\(drawCount)まい" }
          button(.type(.button), .class("big-button")) { "はじめる" }
            .onClick { start() }
          p(.class("hint hint-keys")) { "スペース か → で はじまるよ" }
        }
        backLink

      case .playing:
        div(.class("progress")) {
          div(.class("progress-side")) {
            if let routes {
              AppRoutes.Link(to: routes.home()) { "✕ やめる" }
            }
          }
          span(.class("progress-count")) { "\(index + 1) / \(cards.count)" }
          div(.class("progress-side progress-timer")) {
            if showTimer {
              LiveTimer(startedAt: startedAt)
            }
          }
        }
        if index < cards.count {
          // The screen is split into two tap zones: left goes back, right goes forward.
          div(.class("card-area")) {
            div(.class("card \(deck.colorClass)")) {
              cards[index].question
              if index > 0 {
                span(.class("card-arrow card-arrow-previous")) {}
              }
              span(.class("card-arrow card-arrow-next")) {}
            }
            // The screen is split into two invisible tap zones: left goes back, right goes forward.
            div(.class("tap-zone tap-previous")) {}
              .onClick { goBack() }
            div(.class("tap-zone tap-next")) {}
              .onClick { advance() }
          }
        }
        p(.class("hint hint-keys")) { "← まえ ／ → か スペース で つぎ" }
        p(.class("hint hint-touch")) { "ひだりを タップで まえ ／ みぎを タップで つぎ" }

      case .finished:
        div(.class("finished")) {
          img(.src(stamp.path), .alt(stamp.label), .class("stamp"))
          div(.class("finished-info")) {
            p(.class("finished-title")) { "おわり！" }
            p(.class("finished-time")) { ClockDisplay(milliseconds: elapsed) }
            p(.class("finished-count")) { "\(cards.count)まい できたね" }
            button(.type(.button), .class("big-button")) { "もういちど" }
              .onClick { phase = .ready }
          }
        }
        backLink
      }
    }
    .attach(BrowserListener.cardKeys { key in handle(key) })
  }

  private var backLink: some View {
    div(.class("back")) {
      if let routes {
        AppRoutes.Link(to: routes.home()) { "カードを えらびなおす" }
      }
    }
  }

  private var drawCount: Int {
    let size = deck.cards(includeZero: includeZero).count
    return count <= 0 || count > size ? size : count
  }

  private func handle(_ key: CardKey) {
    switch (phase, key) {
    case (.ready, .next):
      start()
    case (.playing, .next):
      advance()
    case (.playing, .previous):
      goBack()
    default:
      break
    }
  }

  private func start() {
    cards = deck.draw(count: count, includeZero: includeZero)
    index = 0
    elapsed = 0
    startedAt = Browser.now()
    phase = .playing
  }

  private func goBack() {
    if index > 0 { index -= 1 }
  }

  private func advance() {
    if index + 1 < cards.count {
      index += 1
    } else {
      elapsed = Browser.now() - startedAt
      stamp = Stamp.random()
      phase = .finished
    }
  }
}

/// Visible running clock. The measurement itself lives in `PlayPage`, so hiding this view does
/// not stop the timer.
@View
struct LiveTimer {
  let startedAt: Double
  @State var now: Double = 0

  var body: some View {
    ClockDisplay(milliseconds: now - startedAt)
      .attach(BrowserListener.interval(milliseconds: 100) { now = Browser.now() })
  }
}

