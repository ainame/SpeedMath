/// Shows elapsed time as `mm:ss.s`. Every glyph sits in a fixed-width cell, so the layout never
/// shifts as digits change, regardless of whether the font has tabular figures.
@View
struct ClockDisplay {
  let milliseconds: Double

  var body: some View {
    span(.class("clock")) {
      for glyph in ClockGlyph.glyphs(milliseconds: milliseconds) {
        span(.class(glyph.isDigit ? "clock-digit" : "clock-separator")) { glyph.text }
      }
    }
  }
}

/// Today's stamp card: six slots filled in the order the stamps were collected.
@View
struct StampsPage {
  @Environment(AppRoutes._routeSetEnvironmentKey) var routes
  @Environment(StampBook.self) var stampBook: StampBook

  var body: some View {
    section(.class("stamp-card")) {
      h2(.class("stamp-card-title")) { "きょうの スタンプ" }
      div(.class("stamp-slots")) {
        for slot in 0..<Stamp.allCases.count {
          StampSlot(stamp: slot < stampBook.stamps.count ? stampBook.stamps[slot] : nil, number: slot + 1)
        }
      }
      p(.class("stamp-card-message")) { message }
      div(.class("back")) {
        if let routes {
          AppRoutes.Link(to: routes.home()) { "もどる" }
        }
      }
    }
    .onAppear { stampBook.refresh() }
  }

  private var message: String {
    let remaining = Stamp.allCases.count - stampBook.stamps.count
    if remaining == 0 { return "ぜんぶ あつめたね！ また あした。" }
    if stampBook.stamps.isEmpty { return "さいごまで やると スタンプが もらえるよ" }
    return "あと \(remaining)こ！"
  }
}

@View
struct StampSlot {
  let stamp: Stamp?
  let number: Int

  var body: some View {
    div(.class("stamp-slot")) {
      if let stamp {
        img(
          .src(stamp.path),
          .alt(stamp.label),
          .class("stamp-slot-image"),
          .style(["--tilt": "\(Stamp.slotTilts[(number - 1) % Stamp.slotTilts.count])deg"])
        )
      } else {
        span(.class("stamp-slot-number")) { "\(number)" }
      }
    }
  }
}

/// Today's finished runs, newest first. The page is fixed like every other screen; only the list
/// scrolls.
@View
struct RecordsPage {
  @Environment(AppRoutes._routeSetEnvironmentKey) var routes
  @Environment(TodayRecords.self) var records: TodayRecords

  var body: some View {
    section(.class("records")) {
      h2(.class("records-title")) { "きょうの きろく" }
      div(.class("records-list")) {
        if records.records.isEmpty {
          p(.class("records-empty")) { "まだ きろくが ないよ。さいごまで やってみよう！" }
        } else {
          for record in records.records.reversed() {
            RecordRow(record: record)
          }
        }
      }
      p(.class("records-summary")) { summary }
      div(.class("back")) {
        if let routes {
          AppRoutes.Link(to: routes.home()) { "もどる" }
        }
      }
    }
    .onAppear { records.refresh() }
  }

  private var summary: String {
    let runs = records.records.count
    let cards = records.records.reduce(0) { $0 + $1.count }
    return runs == 0 ? "" : "\(runs)かい ・ ぜんぶで \(cards)まい"
  }
}

/// Material-style list item: a leading avatar with the operator, a headline with supporting text,
/// and the elapsed time as the trailing value.
@View
struct RecordRow {
  let record: PlayRecord

  var body: some View {
    div(.class("record-row \(record.deck.colorClass)")) {
      span(.class("record-avatar")) { record.deck.symbol }
      div(.class("record-text")) {
        p(.class("record-headline")) { "\(record.deck.title)（\(record.deck.subtitle)）" }
        p(.class("record-supporting")) {
          "\(record.count)まい ・ \(record.includeZero ? "0あり" : "0なし") ・ \(record.finishedAt)"
        }
      }
      ClockDisplay(milliseconds: Double(record.milliseconds))
    }
  }
}
