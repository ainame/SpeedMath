@View
struct HomePage {
  @Environment(AppRoutes._routeSetEnvironmentKey) var routes
  @Environment(PlaySettings.self) var settings: PlaySettings
  @Environment(StampBook.self) var stampBook: StampBook

  var body: some View {
    section(.class("home")) {
      if let routes {
        div(.class("home-links")) {
          AppRoutes.Link(to: routes.records()) { "きろく" }
          AppRoutes.Link(to: routes.stamps()) {
            "スタンプ \(stampBook.stamps.count)/\(Stamp.allCases.count)"
          }
        }
      }
      div(.class("home-decks")) {
        h2(.class("step")) { "1. カードを えらぼう" }
        div(.class("deck-grid")) {
          for deck in Deck.allCases {
            DeckButton(
              deck: deck,
              size: deck.cards(includeZero: settings.includeZero).count,
              isSelected: settings.deck == deck
            ) { settings.deck = deck }
          }
        }
      }

      div(.class("home-options")) {
        div {
          h2(.class("step")) { "2. 0の けいさん" }
          div(.class("chips")) {
            Chip(label: "いれない", isSelected: !settings.includeZero) { settings.includeZero = false }
            Chip(label: "いれる", isSelected: settings.includeZero) { settings.includeZero = true }
          }
        }
        div {
          h2(.class("step")) { "3. なんまい やる？" }
          div(.class("chips")) {
            // 45 is offered only for decks larger than that; on the 36-card decks it equals "all".
            if settings.deckSize > 45 {
              Chip(label: "45まい", isSelected: settings.count == 45) { settings.count = 45 }
            }
            Chip(
              label: "ぜんぶ",
              isSelected: settings.count <= 0 || settings.count >= settings.deckSize
            ) { settings.count = 0 }
          }
        }
        div {
          h2(.class("step")) { "4. タイマー" }
          div(.class("chips")) {
            Chip(label: "みせる", isSelected: settings.showTimer) { settings.showTimer = true }
            Chip(label: "かくす", isSelected: !settings.showTimer) { settings.showTimer = false }
          }
        }
      }

      div(.class("home-start")) {
        if let routes,
          let destination = try? routes.play(
            deck: settings.deck,
            count: settings.count,
            timer: settings.showTimer,
            zero: settings.includeZero
          )
        {
          AppRoutes.Link(to: destination) { "スタート！" }
        }
      }

      // Static page generated by Scripts/generate-licenses.py, outside the router.
      a(.href("licenses.html"), .class("license-link")) { "ライセンス" }
    }
    .onAppear { stampBook.refresh() }
  }
}

